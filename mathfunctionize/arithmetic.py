def arithmeticAddition(a, b):
    return a + b
def arithmeticSubtraction(a, b):
    return a - b
def arithmeticMultiplication(a, b):
    return a * b
def arithmeticDivision(a, b):
    return a / b
def arithmeticPower(a, b):
    return a ** b
def arithmeticModulo(a, b):
    return a % b
def arithmeticFlatDivision(a, b):
    return a // b